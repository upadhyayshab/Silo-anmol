def note(key: str, lang: str = "en", **values) -> str:
    template = NOTES.get(lang, {}).get(key) or NOTES["en"][key]
    return template.format(**values)


def soil_name(soil_class: Optional[int], lang: str = "en") -> str:
    english = SOIL_TEXTURE_CLASSES.get(soil_class, "Unknown")
    return SOIL_NAMES.get(lang, {}).get(soil_class, english)


def season_name(season: str, lang: str = "en") -> str:
    return SEASON_NAMES.get(lang, {}).get(season) or SEASON_NAMES["en"].get(season, season.title())


def reason_template(factor: str, points: int, lang: str = "en") -> Optional[str]:
    return REASONS.get(lang, {}).get(factor, {}).get(points) or REASONS["en"].get(factor, {}).get(points)


def previous_crop_fallback(lang: str = "en") -> str:
    return PREVIOUS_CROP_FALLBACK.get(lang, PREVIOUS_CROP_FALLBACK["en"])


def suitability_reason(pct: float, season: str, lang: str = "en") -> str:
    template = SUITABILITY.get(lang, SUITABILITY["en"])
    # English keeps its title-case season word ("Kharif"); others use their own name.
    season_label = season.title() if lang not in SUITABILITY or lang == "en" else season_name(season, lang)
    return template.format(pct=f"{pct:.0f}", season=season_label)


